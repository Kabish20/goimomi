/**
 * Normalizes and cleans airport names for display.
 */
export function cleanAirportDisplayName(name) {
  if (!name) return '';
  return name
    .replace(/^(\(Duplicate\))+/i, '')
    .trim();
}

/**
 * Merges backend airports with curated popular airports.
 * Ensures popular airports stay at the top and have clean names,
 * while allowing all 8000+ airports from backend to be searched.
 */
export function mergeAirportData(backendAirports = []) {
  const map = new Map();

  // 1. Add popular airports first to establish priority order
  POPULAR_AIRPORTS.forEach(item => {
    map.set(item.iata_code.toUpperCase(), { ...item });
  });

  // 2. Add backend airports, without overwriting curated popular display titles
  if (Array.isArray(backendAirports)) {
    backendAirports.forEach(item => {
      const code = (item.iata_code || '').trim().toUpperCase();
      if (!code || code.length !== 3) return;

      const existing = map.get(code);
      if (existing) {
        // Enrich country_name or id if missing
        if (!existing.country_name && item.country_name) existing.country_name = item.country_name;
        if (!existing.city_name && item.city_name) existing.city_name = item.city_name;
        if (!existing.id && item.id) existing.id = item.id;
      } else {
        map.set(code, {
          id: item.id,
          iata_code: code,
          city_name: item.city_name || item.name,
          name: cleanAirportDisplayName(item.name),
          country_name: item.country_name || (item.city_name ? 'India' : ''),
          popular: false,
        });
      }
    });
  }

  return Array.from(map.values());
}

/**
 * Intelligent airport search ranking:
 * 1. Exact IATA code (score 100)
 * 2. IATA code starts with query (score 80)
 * 3. City name starts with query (score 65)
 * 4. City name contains query (score 45)
 * 5. Airport name contains query (score 25)
 * 6. Country name contains query (score 15)
 * Boost popular airports slightly for natural matching.
 */
export function filterAirports(query, airportsList = []) {
  const q = (query || '').trim().toLowerCase();
  if (!q) {
    // When no query is entered, return the curated popular airports in strict order
    return airportsList.slice(0, 30);
  }

  const scored = [];
  const len = airportsList.length;

  for (let i = 0; i < len; i++) {
    const item = airportsList[i];
    const code = (item.iata_code || '').toLowerCase();
    const city = (item.city_name || '').toLowerCase();
    const name = (item.name || '').toLowerCase();
    const country = (item.country_name || '').toLowerCase();

    let score = 0;

    if (code === q) {
      score = 100;
    } else if (code.startsWith(q)) {
      score = 80;
    } else if (city === q) {
      score = 75;
    } else if (city.startsWith(q)) {
      score = 65;
    } else if (city.includes(q)) {
      score = 45;
    } else if (name.includes(q)) {
      score = 25;
    } else if (country.includes(q)) {
      score = 15;
    }

    if (score > 0) {
      // Small bonus for popular airports to resolve ties
      if (item.popular) score += 5;
      scored.push({ item, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, 25).map(s => s.item);
}
